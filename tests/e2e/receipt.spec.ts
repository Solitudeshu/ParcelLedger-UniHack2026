import { test, expect } from "@playwright/test";
import { readFileSync } from "node:fs";

test("recipient invitation, interrupted photo upload and recovery", async ({page, browser}) => {
  const code = `QA-PHOTO-${Date.now()}`;
  const before = "tests/fixtures/images/dispatch.png";
  const after = "tests/fixtures/images/changed.png";
  await page.goto("/");
  await page.getByRole("button", {name:"Vào vai người gửi"}).click();
  await page.getByRole("button", {name:"Tạo hồ sơ mới"}).click();
  await page.getByLabel("Mã kiện / mã đơn").fill(code);
  await page.getByLabel("Tên hàng", {exact:true}).fill("Kiện kiểm tra bổ sung ảnh");
  await page.getByLabel("Tên người nhận").fill("Người nhận mẫu");
  await page.getByRole("button", {name:"Tạo và thêm ảnh"}).click();
  await page.locator('input[type=file][multiple]').setInputFiles(before);
  await page.getByRole("button", {name:"Tải ảnh lên hồ sơ"}).click();
  await page.getByRole("button", {name:"Khóa 1 ảnh"}).click();
  await page.getByRole("button", {name:"Lấy link người nhận"}).click();
  const link = await page.getByLabel("Liên kết riêng").inputValue();
  const receiver = await browser.newPage();
  try {
    await receiver.goto(link);
    await expect(receiver.getByRole("heading", {name:"Mở hồ sơ được mời"})).toBeVisible();
    await receiver.reload();
    await receiver.getByRole("button", {name:"Vào vai người nhận"}).click();
    await receiver.getByRole("button", {name:"Tham gia hồ sơ"}).click();
    const picker = receiver.locator('input[type=file][multiple]');
    await picker.setInputFiles([{name:"changed.png", mimeType:"image/png", buffer:readFileSync(after)},
      {name:"bad.txt", mimeType:"text/plain", buffer:Buffer.from("invalid")}]);
    await receiver.getByRole("button", {name:"Tải ảnh lên hồ sơ"}).click();
    await expect(receiver.locator("main").getByRole("alert")).toContainText("bad.txt");
    await expect(receiver.locator(".capture-thumb")).toHaveCount(0);
    await picker.setInputFiles([after,before]);
    let intents = 0;
    await receiver.route("**/uploads", route => ++intents === 2 ? route.abort() : route.continue());
    await receiver.getByRole("button", {name:"Tải ảnh lên hồ sơ"}).click();
    await expect(receiver.locator(".capture-thumb")).toHaveCount(1);
    await expect(receiver.locator(".pending-files")).toContainText("dispatch.png");
    await expect(receiver.getByRole("button", {name:"Đối chiếu và tạo biên bản"})).toHaveCount(0);
    await receiver.getByRole("button", {name:"Tải ảnh lên hồ sơ"}).click();
    await receiver.getByRole("button", {name:"Khóa 2 ảnh"}).click();
    await expect(receiver.getByRole("combobox", {name:"Ảnh nhận cần kiểm tra",exact:true}).locator("option")).toHaveCount(2);
    await receiver.getByRole("button", {name:"Khoanh vùng trên ảnh nhận"}).click();
    await receiver.getByAltText("Ảnh lúc người nhận kiểm tra kiện hàng").click();
    await expect(receiver.getByRole("button", {name:"Dùng toàn ảnh"})).toHaveCount(0);
    await page.locator(".supplement-panel > summary").click();
    await page.locator('input[type=file][multiple]').setInputFiles(after);
    await page.getByRole("button", {name:"Tải ảnh lên hồ sơ"}).click();
    await expect(page.getByRole("button", {name:"Khóa 1 ảnh"})).toBeVisible();
    await receiver.getByRole("button", {name:"Về danh sách hồ sơ",exact:true}).click();
    await receiver.getByRole("textbox", {name:"Tìm hồ sơ"}).fill(code);
    const row = receiver.getByRole("button").filter({hasText:code});
    await receiver.route("**/assets", route => route.abort(), {times:1});
    await row.click();
    await expect(receiver.getByRole("button",{name:"Thử mở lại"})).toBeVisible();
    await expect(receiver.getByText("Đang mở hồ sơ…", {exact:true})).toHaveCount(0);
    await receiver.getByRole("button",{name:"Thử mở lại"}).click();
    await receiver.locator(".supplement-panel > summary").click();
    await receiver.locator('input[type=file][multiple]').setInputFiles(before);
    await receiver.getByRole("button", {name:"Tải ảnh lên hồ sơ"}).click();
    await receiver.getByRole("button", {name:"Khóa 1 ảnh"}).click();
    await expect(receiver.getByRole("combobox", {name:"Ảnh nhận cần kiểm tra",exact:true}).locator("option")).toHaveCount(3);
    await page.getByRole("button", {name:"Khóa 1 ảnh"}).click();
    await expect(page.getByText("Ảnh bổ sung của bên gửi (1)")).toBeVisible();
    await expect(page.getByRole("combobox", {name:"Ảnh nhận cần kiểm tra",exact:true}).locator("option")).toHaveCount(3);
    await page.getByRole("button", {name:"Về danh sách hồ sơ",exact:true}).click();
    await page.getByRole("button", {name:"Tạo hồ sơ mới"}).click();
    await page.getByLabel("Mã kiện / mã đơn").fill(code);
    await page.getByLabel("Tên hàng",{exact:true}).fill("Thử mã trùng");
    await page.getByLabel("Tên người nhận").fill("Minh");
    await page.getByRole("button",{name:"Tạo và thêm ảnh"}).click();
    await expect(page.getByRole("dialog").getByRole("alert")).toContainText("Mã kiện này đã có");
  } finally {await receiver.close();}
});
