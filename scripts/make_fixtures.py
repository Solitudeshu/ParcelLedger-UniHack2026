"""Own procedural fixtures: software regression only, never AI evaluation evidence."""

import hashlib
import json
import random
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageEnhance


def make_images(root: Path):
    root.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(26)
    canvas = np.clip(rng.normal([183, 151, 107], 7, (600, 800, 3)), 0, 255).astype("uint8")
    image = Image.fromarray(canvas)
    draw = ImageDraw.Draw(image)
    randomizer = random.Random(26)
    draw.rectangle((15, 15, 785, 585), outline=(90, 65, 35), width=5)
    draw.rectangle((350, 0, 415, 600), fill=(161, 126, 78))
    draw.rectangle((55, 65, 270, 200), fill=(235, 229, 207))
    draw.text(
        (75, 85), "KIEN CHUNG - SYNTHETIC\nWORKFLOW FIXTURE 026", fill=(20, 20, 20), spacing=6
    )
    for _ in range(130):
        x, y = randomizer.randint(25, 760), randomizer.randint(25, 560)
        color = tuple(randomizer.randint(30, 150) for _ in range(3))
        draw.rectangle(
            (x, y, x + randomizer.randint(3, 22), y + randomizer.randint(3, 18)),
            outline=color,
            width=2,
        )
    image.save(root / "dispatch.png")
    image.save(root / "unchanged.png")
    ImageEnhance.Brightness(image).enhance(0.8).save(root / "lighting.png")
    changed = image.copy()
    ImageDraw.Draw(changed).polygon(
        [(560, 300), (640, 315), (650, 390), (580, 415), (555, 370)], fill=(65, 45, 30)
    )
    changed.save(root / "changed.png")
    image.resize((90, 68)).resize(image.size).save(root / "low-detail.png")
    Image.new("RGB", (800, 600), (180, 150, 105)).save(root / "no-reference.png")
    files = {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in root.glob("*.png")}
    (root / "provenance.json").write_text(
        json.dumps(
            {
                "source": "Generated by scripts/make_fixtures.py",
                "license": "CC0-1.0",
                "synthetic": True,
                "use": "Software regression fixtures, not model performance evidence",
                "files": files,
            },
            indent=2,
        ),
        encoding="utf-8",
    )


def make_vectors(root: Path):
    root.mkdir(parents=True, exist_ok=True)
    cases = [
        ("vietnamese_nfc", {"title": "Kiện chứng", "a": None}, '{"a":null,"title":"Kiện chứng"}'),
        (
            "money_and_escape",
            {"z": 'line\nquote"', "money": "999999999999999999999999", "n": -12},
            '{"money":"999999999999999999999999","n":-12,"z":"line\\nquote\\""}',
        ),
        (
            "report_revision",
            {"version": 2, "parent_hash": "ab" * 32, "observations": [], "approved": False},
            '{"approved":false,"observations":[],"parent_hash":"' + "ab" * 32 + '","version":2}',
        ),
        (
            "ecmascript_number",
            {"tiny": 1e-7, "minus_zero": -0.0, "decimal": 4.5},
            '{"decimal":4.5,"minus_zero":0,"tiny":1e-7}',
        ),
        ("utf16_key_order", {"\uffff": 2, "\U0001f600": 1}, '{"😀":1,"￿":2}'),
    ]
    vectors = [
        {
            "name": name,
            "document": document,
            "canonical": canonical,
            "sha256": hashlib.sha256(canonical.encode()).hexdigest(),
        }
        for name, document, canonical in cases
    ]
    (root / "canonical-v1.json").write_text(
        json.dumps(vectors, ensure_ascii=False, indent=2), encoding="utf-8"
    )


if __name__ == "__main__":
    make_images(Path("tests/fixtures/images"))
    make_vectors(Path("tests/fixtures"))
